// Regenerates src/lib/demo/embedded-launch.ts (the sample launch poster) so the seed does not need server fonts.
// Usage: npx tsx scripts/build-launch-poster.ts
import { writeFileSync } from "node:fs";
import { makeLaunchPoster } from "../src/lib/demo/assets";

(async () => {
  const png = await makeLaunchPoster();
  writeFileSync("src/lib/demo/embedded-launch.ts", `// Generated by scripts/build-launch-poster.ts — do not edit by hand.\nexport const DEMO_LAUNCH_POSTER_PNG = "${png.toString("base64")}";\n`);
  console.log(`launch poster ${png.length} B`);
})();
