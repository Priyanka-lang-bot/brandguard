// Regenerates src/lib/demo/embedded.ts (demo poster and logos as base64 PNG) so the seed does not depend on
// fonts being installed on the server. Usage: npx tsx scripts/build-demo-assets.ts
import { writeFileSync } from "node:fs";
import { makeLogo, makePoster, makeRetiredLogo } from "../src/lib/demo/assets";

(async () => {
  const [poster, logo, retired] = await Promise.all([makePoster(), makeLogo(), makeRetiredLogo()]);
  const out = `// Generated by scripts/build-demo-assets.ts — do not edit by hand.
export const DEMO_POSTER_PNG = "${poster.toString("base64")}";
export const DEMO_LOGO_PNG = "${logo.toString("base64")}";
export const DEMO_RETIRED_LOGO_PNG = "${retired.toString("base64")}";
`;
  writeFileSync("src/lib/demo/embedded.ts", out);
  console.log(`poster ${poster.length} B, logo ${logo.length} B, retired ${retired.length} B`);
})();
